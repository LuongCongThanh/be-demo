// Conventional Commits + chặn AI attribution (docs/convention/git-workflow.md).
import { validateCommitMessage } from './scripts/git-policy.mjs';

export default {
  extends: ['@commitlint/config-conventional'],
  rules: {
    'type-enum': [
      2,
      'always',
      ['feat', 'fix', 'refactor', 'test', 'docs', 'chore', 'style', 'perf', 'ci', 'build', 'revert', 'security'],
    ],
    'header-max-length': [2, 'always', 100],
    'no-ai-attribution': [2, 'always'],
  },
  plugins: [
    {
      rules: {
        'no-ai-attribution': ({ raw }) => [
          validateCommitMessage(raw ?? '').valid,
          'Commit message không được chứa AI/tool/agent attribution (Co-Authored-By hoặc Generated by/with)',
        ],
      },
    },
  ],
};
