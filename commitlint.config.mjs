// Conventional Commits + chặn AI attribution (docs/convention/git-workflow.md).
const AI_ATTRIBUTION =
  /(co-authored-by:\s*claude|generated (with|by) (claude|ai)|ai-generated|noreply@anthropic\.com)/i;

export default {
  extends: ['@commitlint/config-conventional'],
  rules: {
    'type-enum': [
      2,
      'always',
      ['feat', 'fix', 'refactor', 'test', 'docs', 'chore', 'style', 'perf', 'ci', 'build', 'revert'],
    ],
    'header-max-length': [2, 'always', 100],
    'no-ai-attribution': [2, 'always'],
  },
  plugins: [
    {
      rules: {
        'no-ai-attribution': ({ raw }) => [
          !AI_ATTRIBUTION.test(raw ?? ''),
          'Commit message không được chứa AI attribution (Co-Authored-By: Claude, Generated by…)',
        ],
      },
    },
  ],
};
